def enrich_modules(modules):
    for module_id, module in modules.items():
        name, description, example, group = MODULE_HELP[module_id]
        module.update(name=name, description=description, explanation=example, group_label=group)
        for key, schema in module.get('params_schema', {}).items():
            label, help_text = PARAM_HELP[key]
            schema.update(label=label, help=help_text)
            if key in ('ma_deviation_ceil', 'last_price_ma30_ceil'):
                schema['advanced'] = True
                schema['read_only'] = True
